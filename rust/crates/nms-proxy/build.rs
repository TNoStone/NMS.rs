//! Windows version information, so the file shows what it is in Explorer
//! and to virus scanners. `NMS_RS_VERSION` (for example 4.0.0) overrides the crate version.
//!
//! With `as-winmm` or `as-version` the DLL is built for that name: one jump stub per export of the
//! System32 DLL (`exports\<name>.txt`), exported under the same name and ordinal.

use std::fmt::Write as _;
use std::path::PathBuf;

/// (Cargo feature, DLL file name). No feature: xinput9_1_0.dll, forwarded by hand in `xinput.rs`.
const VARIANTS: &[(&str, &str)] = &[("AS_WINMM", "winmm.dll"), ("AS_VERSION", "version.dll")];

fn main() {
    println!("cargo:rerun-if-env-changed=NMS_RS_VERSION");
    println!("cargo:rustc-check-cfg=cfg(nms_proxy_forward)");
    let picked: Vec<&str> = VARIANTS
        .iter()
        .filter(|(feature, _)| std::env::var_os(format!("CARGO_FEATURE_{feature}")).is_some())
        .map(|(_, dll)| *dll)
        .collect();
    if picked.len() > 1 {
        panic!("nms-proxy: pick one DLL name feature at a time, not {}", picked.join(" and "));
    }
    let dll = picked.first().copied().unwrap_or("xinput9_1_0.dll");
    if dll != "xinput9_1_0.dll" {
        println!("cargo:rustc-cfg=nms_proxy_forward");
        forward_stubs(dll);
    }
    version_info(dll);
}

/// `OUT_DIR\forward_gen.rs` (export table and stubs) and one `/EXPORT` linker argument per export.
fn forward_stubs(dll: &str) {
    let stem = dll.trim_end_matches(".dll");
    let list = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("exports").join(format!("{stem}.txt"));
    println!("cargo:rerun-if-changed={}", list.display());
    let text = std::fs::read_to_string(&list).unwrap_or_else(|e| panic!("{}: {e}", list.display()));
    let mut table = String::new();
    let mut asm = String::new();
    let mut used_ordinals = std::collections::HashSet::new();
    let mut count = 0usize;
    for line in text.lines().map(str::trim).filter(|l| !l.is_empty() && !l.starts_with('#')) {
        let (ordinal, name) = line.split_once(' ').unwrap_or_else(|| panic!("{}: bad line {line:?}", list.display()));
        let ordinal: u16 = ordinal.parse().unwrap_or_else(|_| panic!("{}: bad ordinal in {line:?}", list.display()));
        let i = count;
        count += 1;
        let stub = format!("__nmsrs_fwd_{i}");
        // An ordinal can carry two names; only the first gets the fixed ordinal.
        let at = if used_ordinals.insert(ordinal) { format!(",@{ordinal}") } else { String::new() };
        if name == "-" {
            writeln!(table, "    Export::Ordinal({ordinal}),").unwrap();
            println!("cargo:rustc-cdylib-link-arg=/EXPORT:__nmsrs_ord_{ordinal}={stub}{at},NONAME");
        } else {
            assert!(name.bytes().all(|b| b.is_ascii_graphic()), "{}: bad export name {name:?}", list.display());
            writeln!(table, "    Export::Name(b\"{name}\\0\"),").unwrap();
            println!("cargo:rustc-cdylib-link-arg=/EXPORT:{name}={stub}{at}");
        }
        writeln!(asm, "    \".globl {stub}\",\n    \".p2align 4\",\n    \"{stub}:\",\n    \"mov eax, {i}\",\n    \"jmp {{common}}\",").unwrap();
    }
    let out = format!(
        "// Generated by build.rs from exports\\{stem}.txt.\n\
         pub(crate) const DLL: &str = \"{dll}\";\n\
         pub(crate) static EXPORTS: [Export; {count}] = [\n{table}];\n\
         static SLOTS: [AtomicUsize; {count}] = [const {{ AtomicUsize::new(0) }}; {count}];\n\
         core::arch::global_asm!(\n{asm}    common = sym fwd_common,\n);\n"
    );
    let path = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("forward_gen.rs");
    std::fs::write(&path, out).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
}

fn version_info(dll: &str) {
    #[cfg(windows)]
    {
        let stem = dll.trim_end_matches(".dll");
        let kind = if stem == "xinput9_1_0" { "XInput" } else { stem };
        let version = std::env::var("NMS_RS_VERSION")
            .unwrap_or_else(|_| std::env::var("CARGO_PKG_VERSION").unwrap_or_else(|_| "0.0.0".into()));
        let mut parts = version.split('.').map(|p| p.parse::<u64>().unwrap_or(0));
        let (major, minor, patch) = (
            parts.next().unwrap_or(0),
            parts.next().unwrap_or(0),
            parts.next().unwrap_or(0),
        );
        let packed = (major << 48) | (minor << 32) | (patch << 16);
        let mut res = winresource::WindowsResource::new();
        res.set_version_info(winresource::VersionInfo::FILEVERSION, packed);
        res.set_version_info(winresource::VersionInfo::PRODUCTVERSION, packed);
        res.set("FileVersion", &version);
        res.set("ProductVersion", &version);
        res.set("ProductName", "NMS.rs");
        res.set("FileDescription", &format!("NMS.rs mod loader ({kind} proxy) for the NMS game"));
        res.set("InternalName", stem);
        res.set("OriginalFilename", dll);
        res.set("LegalCopyright", "GPL-3.0-or-later");
        if let Err(err) = res.compile() {
            println!("cargo:warning=version information not embedded: {err}");
        }
    }
    #[cfg(not(windows))]
    let _ = dll;
}
